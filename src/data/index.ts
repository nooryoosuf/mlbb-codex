// The JSON is generated by scripts/build_dataset.py; its inferred literal types
// are wider than the interfaces above (e.g. number[] for stat ranges), so the
// cast goes through unknown once here and the rest of the app stays typed.
export const heroes = rawHeroes as unknown as Hero[];
export const items = rawItems as unknown as Item[];
export const patches = rawPatches as unknown as Patch[];
export const meta = rawMeta as unknown as MetaSnapshot;
export const patchNotes = rawPatchNotes as unknown as {
    source: string;
    attribution: string;
    patches: PatchNotes[];
};

export const ROLES: Role[] = ["Tank", "Fighter", "Assassin", "Mage", "Marksman", "Support"];
export const LANES: Lane[] = ["Gold Lane", "Exp Lane", "Mid Lane", "Jungle", "Roam"];

export const heroById = new Map(heroes.map((hero) => [hero.slug, hero]));
export const heroByName = new Map(heroes.map((hero) => [hero.name.toLowerCase(), hero]));
export const itemById = new Map(items.map((item) => [item.slug, item]));
export const metaBySlug = new Map(meta.heroes.map((entry) => [entry.slug, entry]));

export function getHero(slug: string): Hero | undefined {
    return heroById.get(slug);
}

export function getItem(slug: string): Item | undefined {
    return itemById.get(slug);
}

export function heroHref(slug: string): string {
    return `/hero/${slug}`;
}

/** Resolve a hero slug or display name to a hero record. */
export function resolveHero(value: string | null | undefined): Hero | undefined {
    if (!value) return undefined;
    return heroById.get(value) ?? heroByName.get(value.toLowerCase());
}

/** Neighbours in alphabetical order, wrapping at the ends. */
export function getHeroNeighbours(slug: string): { previous: Hero; next: Hero } | undefined {
    const index = heroes.findIndex((hero) => hero.slug === slug);
    if (index === -1 || heroes.length < 2) return undefined;
    return {
        previous: heroes[(index - 1 + heroes.length) % heroes.length],
        next: heroes[(index + 1) % heroes.length],
    };
}

export function getRelatedHeroes(hero: Hero, limit = 6): Hero[] {
    const seen = new Set<string>([hero.slug]);
    const ordered = [...hero.synergies, ...hero.strongAgainst, ...hero.weakAgainst];
    const related: Hero[] = [];
    for (const slug of ordered) {
        const found = heroById.get(slug);
        if (!found || seen.has(found.slug)) continue;
        seen.add(found.slug);
        related.push(found);
        if (related.length >= limit) break;
    }
    return related;
}

/** Deterministic hero of the day based on the UTC date. */
export function getHeroOfTheDay(date = new Date()): Hero {
    const dayNumber = Math.floor(Date.UTC(date.getUTCFullYear(), date.getUTCMonth(), date.getUTCDate()) / 86_400_000);
    return heroes[dayNumber % heroes.length];
}

export function getLatestPatch(): Patch | undefined {
    return patches[0];
}

export function getMetaHero(slug: string): MetaHero | undefined {
    return metaBySlug.get(slug);
}

export function getLatestPatchNotes(): PatchNotes | undefined {
    return patchNotes.patches[0];
}

/** Count of heroes per role, sorted by the canonical role order. */
export function countByRole(): { role: Role; count: number }[] {
    return ROLES.map((role) => ({
        role,
        count: heroes.filter((hero) => hero.roles.includes(role)).length,
    })).filter((entry) => entry.count > 0);
}

export function countByLane(): { lane: Lane; count: number }[] {
    return LANES.map((lane) => ({
        lane,
        count: heroes.filter((hero) => hero.lanes.includes(lane)).length,
    })).filter((entry) => entry.count > 0);
}

export function formatStat(value: number | null | undefined): string {
    if (value === null || value === undefined) return "—";
    return Number.isInteger(value) ? value.toLocaleString("en-US") : value.toFixed(1);
}

export function statRange(range: [number, number] | null): string {
    if (!range) return "—";
    const [low, high] = range;
    return `${formatStat(low)} → ${formatStat(high)}`;
}
